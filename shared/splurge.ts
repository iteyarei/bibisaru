/** Pick a pool name. The same name is not returned twice in a row when the pool has another choice. */
export function pickSplurgeName(previous = "", random: () => number = Math.random): string {
  const names = SPLURGE_NAMES;
  const index = Math.min(names.length - 1, Math.max(0, Math.floor(random() * names.length)));
  const chosen = names[index] ?? names[0];
  if (chosen !== previous) return chosen;
  const offset = 1 + Math.floor(random() * (names.length - 1));
  return names[(index + offset) % names.length] ?? chosen;
}
